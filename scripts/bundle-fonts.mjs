// Downloads the app's fonts (open-licence Google Fonts, woff2) into www/assets/fonts and writes fonts.css,
// so the app never needs the internet for typography.   node scripts/bundle-fonts.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'www', 'assets', 'fonts');
fs.mkdirSync(OUT, { recursive: true });
export const FONTS = [
  ['Sora', '300..800'], ['Inter', '400..800'], ['Space Grotesk', '400..700'], ['Unbounded', '400..800'], ['JetBrains Mono', '400..800'],
  ['Poppins', null, [400, 500, 600, 700, 800]], ['Manrope', '400..800'], ['Outfit', '300..800'], ['DM Sans', '400..800'], ['Plus Jakarta Sans', '400..800'],
  ['Urbanist', '400..800'], ['Lexend', '400..800'], ['Rubik', '400..800'], ['Nunito', '400..800'], ['Montserrat', '400..800'],
  ['Orbitron', '400..800'], ['Exo 2', '400..800'], ['Audiowide', null, [400]], ['Playfair Display', '400..800'], ['Cormorant Garamond', null, [500, 600, 700]],
  ['Righteous', null, [400]], ['Space Mono', null, [400, 700]], ['Quicksand', '400..700'], ['Comfortaa', '400..700'], ['Baloo 2', '400..800'],
];
const UA = 'Mozilla/5.0 (Linux; Android 14) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Mobile Safari/537.36';
let css = '/* bundled fonts — generated by scripts/bundle-fonts.mjs */\n';
for (const [fam, range, weights] of FONTS) {
  const spec = range ? `${fam.replace(/ /g, '+')}:wght@${range}` : `${fam.replace(/ /g, '+')}:wght@${weights.join(';')}`;
  const r = await fetch(`https://fonts.googleapis.com/css2?family=${spec}&display=swap`, { headers: { 'User-Agent': UA } });
  if (!r.ok) { console.warn('skip', fam, r.status); continue; }
  let txt = await r.text();
  // keep latin + latin-ext + devanagari subsets (what the app and Indian names use)
  const blocks = txt.split('/* ').slice(1).filter(b => /^(latin|latin-ext|devanagari) \*\//.test(b));
  for (const b of blocks) {
    const sub = b.slice(0, b.indexOf(' */'));
    const url = (b.match(/url\((https:[^)]+\.woff2)\)/) || [])[1]; if (!url) continue;
    const w = (b.match(/font-weight: ([^;]+);/) || [])[1].replace(/ /g, '-');
    const file = `${fam.replace(/ /g, '')}-${sub}-${w}.woff2`;
    if (!fs.existsSync(path.join(OUT, file))) fs.writeFileSync(path.join(OUT, file), Buffer.from(await (await fetch(url, { headers: { 'User-Agent': UA } })).arrayBuffer()));
    css += '/* ' + b.replace(url, `assets/fonts/${file}`).replace(/url\(assets/, 'url(../assets');
  }
  console.log('✓', fam);
}
fs.writeFileSync(path.join(ROOT, 'www', 'css', 'fonts.css'), css);
console.log('fonts.css written');
